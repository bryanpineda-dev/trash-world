function leafSprig(d,x,y,side=1) {
  d.poly([[x,y],[x+side*3,y-2],[x+side*5,y-1],[x+side*4,y+1],[x+side,y+1]],'w');
  d.line([[x+side,y],[x+side*3,y-1]],'x');
}

