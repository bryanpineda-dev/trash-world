export function raster(width, height) {
  const rows = Array.from({ length:height },()=>Array(width).fill('.'));
  const pixel = (x,y,ink,mask) => {
    x=Math.round(x); y=Math.round(y);
    if (x>=0 && x<width && y>=0 && y<height && (!mask || mask.includes(rows[y][x]))) rows[y][x]=ink;
  };
  const rect = (x,y,w,h,ink,mask) => { for(let dy=0;dy<h;dy++)for(let dx=0;dx<w;dx++)pixel(x+dx,y+dy,ink,mask); };
  const line = (points,ink,mask) => {
    for(let i=1;i<points.length;i++) {
      const [ax,ay]=points[i-1], [bx,by]=points[i], n=Math.max(Math.abs(bx-ax),Math.abs(by-ay),1);
      for(let j=0;j<=n;j++)pixel(ax+(bx-ax)*j/n,ay+(by-ay)*j/n,ink,mask);
    }
  };
  const poly = (points,ink,mask) => {
    for(let y=Math.max(0,Math.floor(Math.min(...points.map(p=>p[1]))));y<=Math.min(height-1,Math.ceil(Math.max(...points.map(p=>p[1]))));y++) {
      const edges=[];
      for(let i=0;i<points.length;i++) {
        const a=points[i], b=points[(i+1)%points.length];
        if((a[1]<=y&&b[1]>y)||(b[1]<=y&&a[1]>y))edges.push(a[0]+(y-a[1])*(b[0]-a[0])/(b[1]-a[1]));
      }
      edges.sort((a,b)=>a-b);
      for(let i=0;i<edges.length;i+=2)for(let x=Math.ceil(edges[i]);x<=Math.floor(edges[i+1]);x++)pixel(x,y,ink,mask);
    }
  };
  return {width,height,rows,pixel,rect,line,poly,
    finish:(id,label,anchor)=>({id,label,size:[width,height],anchor,pixels:rows.map(r=>r.join(''))})};
}

