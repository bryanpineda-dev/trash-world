function plinth(d,x,y,w) {
  d.poly([[x,y],[x+w-4,y],[x+w,y+3],[x+w,y+6],[x-2,y+6],[x-2,y+3]],'o');
  d.poly([[x,y],[x+w-4,y],[x+w,y+3],[x+1,y+3],[x-2,y+2]],'s');
  d.rect(x,y+4,w-1,2,'p');d.line([[x,y+3],[x+w-1,y+3]],'r');
}
function moss(d,patches,mask=stone) {
  for(const [x,y,w,h] of patches) {
    d.poly([[x,y+1],[x+2,y],[x+w-1,y],[x+w,y+2],[x+w-2,y+h],[x+1,y+h],[x,y+h-1]],'v',mask+'vwxy');
    d.poly([[x+1,y],[x+w-1,y],[x+w,y+1],[x+w-2,y+2],[x+1,y+2]],'x',mask+'vwxy');
    d.line([[x+2,y],[x+w-2,y]],'y',mask+'vwxy');
    if(h>4)d.line([[x+w-2,y+2],[x+w-3,y+h]],'w',mask+'vwxy');
  }
}
